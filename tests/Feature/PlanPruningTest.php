<?php

namespace Tests\Feature;

use App\Enums\WorkoutSessionStatus;
use App\Models\Partner;
use App\Models\Plan;
use App\Models\WorkoutSession;
use App\Models\WorkoutTemplate;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Storage;
use Tests\TestCase;

/**
 * Untrained Programs: an inactive generated Program nobody completed a
 * session of is discarded a week after it was last touched.
 */
class PlanPruningTest extends TestCase
{
    use RefreshDatabase;

    private function untrained(int $daysInactive = 8, array $attributes = []): Plan
    {
        return Plan::factory()->program()->autoGenerated()->create([
            'is_active' => false,
            'updated_at' => now()->subDays($daysInactive),
            ...$attributes,
        ]);
    }

    private function sessionOf(Plan $plan, WorkoutSessionStatus $status): WorkoutSession
    {
        return WorkoutSession::factory()->create([
            'user_id' => $plan->user_id,
            'workout_template_id' => WorkoutTemplate::factory()->for($plan)->create()->id,
            'status' => $status,
        ]);
    }

    private function prune(): void
    {
        $this->artisan('model:prune', ['--model' => [Plan::class]])->assertSuccessful();
    }

    public function test_an_untrained_program_inactive_for_over_a_week_is_pruned(): void
    {
        $plan = $this->untrained();

        $this->prune();

        $this->assertModelMissing($plan);
    }

    public function test_its_workouts_go_with_it_and_sessions_run_from_them_keep_their_history(): void
    {
        $plan = $this->untrained();
        $abandoned = $this->sessionOf($plan, WorkoutSessionStatus::Cancelled);
        $template = $abandoned->workoutTemplate;

        $this->prune();

        $this->assertModelMissing($template);
        $this->assertModelExists($abandoned);
        $this->assertNull($abandoned->fresh()->workout_template_id);
    }

    public function test_its_cover_image_is_deleted(): void
    {
        Storage::fake();
        Storage::put('plans/covers/cover.jpg', 'image');
        $plan = $this->untrained(attributes: ['cover_image' => 'plans/covers/cover.jpg']);

        $this->prune();

        $this->assertModelMissing($plan);
        Storage::assertMissing('plans/covers/cover.jpg');
    }

    public function test_a_program_with_a_completed_session_is_kept(): void
    {
        $plan = $this->untrained();
        $this->sessionOf($plan, WorkoutSessionStatus::Completed);

        $this->prune();

        $this->assertModelExists($plan);
    }

    public function test_a_program_switched_away_from_within_the_week_is_kept(): void
    {
        $plan = $this->untrained(daysInactive: 6);

        $this->prune();

        $this->assertModelExists($plan);
    }

    public function test_active_hand_made_and_library_plans_are_never_pruned(): void
    {
        $active = Plan::factory()->program()->autoGenerated()->create([
            'is_active' => true,
            'updated_at' => now()->subDays(30),
        ]);
        $handMade = Plan::factory()->program()->create([
            'is_active' => false,
            'updated_at' => now()->subDays(30),
        ]);
        $library = Plan::factory()->partnerLibrary(Partner::factory()->create())->autoGenerated()->create([
            'is_active' => false,
            'updated_at' => now()->subDays(30),
        ]);

        $this->prune();

        $this->assertModelExists($active);
        $this->assertModelExists($handMade);
        $this->assertModelExists($library);
    }
}
